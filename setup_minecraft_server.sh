#!/bin/bash

# --- Configuration Variables ---
MINECRAFT_VERSION="1.20.4" # The Minecraft server version to set up.
SERVER_DIR="minecraft_server_${MINECRAFT_VERSION}" # Directory where server files will be stored.
SERVER_JAR_URL="https://piston-data.mojang.com/v1/objects/8dd1a280150651b1913256a7463f1b580f5c9e29/server.jar" # Direct download URL for the server JAR.
SERVER_JAR_NAME="server.jar" # The name of the downloaded server JAR file.
JAVA_MEMORY_ARGS="-Xmx1024M -Xms1024M" # Java memory arguments (e.g., 1GB RAM).

# --- Helper Function to Check for Required Commands ---
check_command() {
    if ! command -v "$1" &> /dev/null; then
        echo "Error: '$1' is not installed. Please install it to proceed." >&2
        exit 1
    fi
}

# --- Main Script Logic ---

echo "--- Minecraft Server Setup Script ---"
echo "This script will set up a basic Minecraft Java Edition server (version ${MINECRAFT_VERSION})."
echo ""

# 1. Check for Java and curl (essential for running and downloading the server).
echo "Checking for required tools (Java, curl)..."
check_command "java"
check_command "curl"
echo "All required tools found."
echo ""

# 2. Create the server directory if it doesn't exist.
if [ -d "$SERVER_DIR" ]; then
    echo "Warning: Directory '$SERVER_DIR' already exists. Existing server files might be used or overwritten."
else
    echo "Creating server directory: '$SERVER_DIR'..."
    mkdir "$SERVER_DIR"
    if [ $? -ne 0 ]; then
        echo "Error: Failed to create directory '$SERVER_DIR'. Exiting." >&2
        exit 1
    fi
    echo "Directory created."
fi

# Change into the server directory to perform operations.
cd "$SERVER_DIR" || { echo "Error: Could not change to directory '$SERVER_DIR'. Exiting." >&2; exit 1; }
echo ""

# 3. Download the Minecraft server JAR file.
if [ -f "$SERVER_JAR_NAME" ]; then
    echo "Server JAR '$SERVER_JAR_NAME' already exists in '$SERVER_DIR'. Skipping download."
else
    echo "Downloading Minecraft server JAR (version ${MINECRAFT_VERSION})..."
    curl -o "$SERVER_JAR_NAME" "$SERVER_JAR_URL"
    if [ $? -ne 0 ]; then
        echo "Error: Failed to download server JAR. Please check the URL and your internet connection. Exiting." >&2
        exit 1
    fi
    echo "Server JAR downloaded successfully."
fi
echo ""

# 4. Create and accept the Minecraft End User License Agreement (EULA).
# The server requires eula.txt to exist with 'eula=true' to start.
if [ -f "eula.txt" ]; then
    echo "eula.txt already exists. Ensuring EULA is accepted."
    if ! grep -q "eula=true" "eula.txt"; then
        echo "eula=true" > eula.txt # Overwrite if not accepted
        echo "eula.txt updated to accept EULA."
    else
        echo "EULA already accepted in eula.txt."
    fi
else
    echo "Creating eula.txt and accepting the Minecraft EULA..."
    echo "eula=true" > eula.txt
    echo "eula.txt created."
    echo "By running this script, you agree to the Minecraft End User License Agreement (EULA)."
    echo "You can review it at: https://aka.ms/MinecraftEULA"
fi
echo ""

# 5. Create a basic server.properties file if it doesn't exist.
# This file configures various aspects of the Minecraft server.
if [ -f "server.properties" ]; then
    echo "server.properties already exists. Skipping creation of default file."
else
    echo "Creating a basic server.properties file..."
    cat << EOF > server.properties
# Minecraft server properties generated by setup script
# For more options, see: https://minecraft.fandom.com/wiki/Server.properties
enable-query=false
enable-rcon=false
motd=A Minecraft Server by Your Guide!
gamemode=survival
difficulty=easy
max-players=20
online-mode=true
pvp=true
allow-flight=false
level-name=world
server-port=25565
view-distance=10
EOF
    echo "server.properties created with basic settings."
fi
echo ""

# 6. Provide instructions on how to run the server.
echo "--- Setup Complete! ---"
echo "Your Minecraft server files are set up in the '$SERVER_DIR' directory."
echo "To start your Minecraft server, navigate into the directory and run the following command:"
echo ""
echo "  cd $SERVER_DIR"
echo "  java ${JAVA_MEMORY_ARGS} -jar ${SERVER_JAR_NAME} nogui"
echo ""
echo "The server will start and generate world files. You can then connect to it using 'localhost' or your server's IP address."
echo "Press Ctrl+C to stop the server once it's running in the terminal."
echo "Remember to open port 25565 in your firewall/router if you want others to connect from outside your local network."
echo ""
